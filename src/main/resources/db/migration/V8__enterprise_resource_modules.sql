-- 1. DEPO & STOK YÖNETİMİ
CREATE TABLE stock_items (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code            VARCHAR2(64 CHAR)  NOT NULL CONSTRAINT uk_stock_items_code UNIQUE,
    item_name            VARCHAR2(255 CHAR) NOT NULL,
    category             VARCHAR2(100 CHAR) NOT NULL,
    warehouse_name       VARCHAR2(180 CHAR) NOT NULL,
    building_id          NUMBER(19)         CONSTRAINT fk_stock_bld REFERENCES buildings (id),
    department_id        NUMBER(19)         CONSTRAINT fk_stock_dept REFERENCES departments (id),
    current_quantity     NUMBER(12, 2)      DEFAULT 0 NOT NULL,
    min_threshold        NUMBER(12, 2)      DEFAULT 10 NOT NULL,
    unit                 VARCHAR2(32 CHAR)  DEFAULT 'Adet' NOT NULL,
    unit_price           NUMBER(15, 2)      DEFAULT 0 NOT NULL,
    status               VARCHAR2(32 CHAR)  DEFAULT 'NORMAL' NOT NULL,
    last_restocked_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_stock_items_cat  ON stock_items (category);
CREATE INDEX idx_stock_items_wh   ON stock_items (warehouse_name);
CREATE INDEX idx_stock_items_stat ON stock_items (status);

CREATE TABLE stock_transactions (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_code     VARCHAR2(64 CHAR)  NOT NULL CONSTRAINT uk_stock_tx_code UNIQUE,
    stock_item_id        NUMBER(19)         NOT NULL CONSTRAINT fk_stock_tx_item REFERENCES stock_items (id) ON DELETE CASCADE,
    tx_type              VARCHAR2(32 CHAR)  NOT NULL, -- 'GIRIS', 'CIKIS', 'SAYIM_DUZELTME'
    quantity             NUMBER(12, 2)      NOT NULL,
    department_id        NUMBER(19)         CONSTRAINT fk_stock_tx_dept REFERENCES departments (id),
    department_name      VARCHAR2(180 CHAR),
    recipient_name       VARCHAR2(180 CHAR),
    performed_by         VARCHAR2(180 CHAR) NOT NULL,
    notes                VARCHAR2(500 CHAR),
    tx_date              TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_stock_tx_item ON stock_transactions (stock_item_id);
CREATE INDEX idx_stock_tx_date ON stock_transactions (tx_date);

-- 2. ARAÇ & FİLO VE İŞ MAKİNESİ YÖNETİMİ
CREATE TABLE fleet_vehicles (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number         VARCHAR2(32 CHAR)  NOT NULL CONSTRAINT uk_fleet_plate UNIQUE,
    vehicle_code         VARCHAR2(48 CHAR)  NOT NULL CONSTRAINT uk_fleet_code UNIQUE,
    vehicle_type         VARCHAR2(64 CHAR)  NOT NULL,
    brand_model          VARCHAR2(180 CHAR) NOT NULL,
    model_year           NUMBER(4)          NOT NULL,
    department_id        NUMBER(19)         CONSTRAINT fk_fleet_dept REFERENCES departments (id),
    department_name      VARCHAR2(180 CHAR) NOT NULL,
    assigned_driver      VARCHAR2(180 CHAR),
    current_km           NUMBER(10)         DEFAULT 0 NOT NULL,
    fuel_type            VARCHAR2(32 CHAR)  DEFAULT 'Dizel' NOT NULL,
    inspection_date      DATE,
    insurance_date       DATE,
    kasko_date           DATE,
    status               VARCHAR2(40 CHAR)  DEFAULT 'Görevde' NOT NULL,
    notes                VARCHAR2(500 CHAR),
    updated_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_fleet_type   ON fleet_vehicles (vehicle_type);
CREATE INDEX idx_fleet_dept   ON fleet_vehicles (department_id);
CREATE INDEX idx_fleet_status ON fleet_vehicles (status);

-- 3. SATIN ALMA & TEDARİK SÜREÇLERİ
CREATE TABLE procurement_orders (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no             VARCHAR2(64 CHAR)  NOT NULL CONSTRAINT uk_proc_order_no UNIQUE,
    title                VARCHAR2(255 CHAR) NOT NULL,
    department_id        NUMBER(19)         CONSTRAINT fk_proc_dept REFERENCES departments (id),
    department_name      VARCHAR2(180 CHAR) NOT NULL,
    procurement_type     VARCHAR2(64 CHAR)  NOT NULL,
    supplier_name        VARCHAR2(180 CHAR) NOT NULL,
    estimated_budget     NUMBER(15, 2)      DEFAULT 0 NOT NULL,
    final_amount         NUMBER(15, 2),
    status               VARCHAR2(40 CHAR)  DEFAULT 'ONAYLANDI' NOT NULL,
    requested_by         VARCHAR2(180 CHAR) NOT NULL,
    order_date           DATE               DEFAULT SYSDATE NOT NULL,
    delivery_date        DATE,
    description          VARCHAR2(1000 CHAR)
);

CREATE INDEX idx_proc_status ON procurement_orders (status);
CREATE INDEX idx_proc_dept   ON procurement_orders (department_id);

-- 4. SAYIM & ENVANTER KONTROLÜ
CREATE TABLE inventory_audits (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_code           VARCHAR2(64 CHAR)  NOT NULL CONSTRAINT uk_audit_code UNIQUE,
    title                VARCHAR2(255 CHAR) NOT NULL,
    building_id          NUMBER(19)         CONSTRAINT fk_audit_bld REFERENCES buildings (id),
    department_id        NUMBER(19)         CONSTRAINT fk_audit_dept REFERENCES departments (id),
    scope_description    VARCHAR2(255 CHAR) NOT NULL,
    total_expected       NUMBER(8)          DEFAULT 0 NOT NULL,
    total_scanned        NUMBER(8)          DEFAULT 0 NOT NULL,
    total_missing        NUMBER(8)          DEFAULT 0 NOT NULL,
    total_excess         NUMBER(8)          DEFAULT 0 NOT NULL,
    status               VARCHAR2(32 CHAR)  DEFAULT 'DEVAM_EDIYOR' NOT NULL,
    started_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    completed_at         TIMESTAMP WITH TIME ZONE,
    lead_auditor         VARCHAR2(180 CHAR) NOT NULL,
    notes                VARCHAR2(500 CHAR)
);

CREATE TABLE audit_scans (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id             NUMBER(19)         NOT NULL CONSTRAINT fk_scan_audit REFERENCES inventory_audits (id) ON DELETE CASCADE,
    asset_id             NUMBER(19)         CONSTRAINT fk_scan_asset REFERENCES assets (id),
    asset_code           VARCHAR2(64 CHAR)  NOT NULL,
    asset_name           VARCHAR2(255 CHAR) NOT NULL,
    expected_location    VARCHAR2(255 CHAR),
    scanned_location     VARCHAR2(255 CHAR) NOT NULL,
    match_status         VARCHAR2(32 CHAR)  DEFAULT 'DOGRU_KONUM' NOT NULL,
    scanned_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    scanned_by           VARCHAR2(180 CHAR) NOT NULL,
    notes                VARCHAR2(255 CHAR)
);

CREATE INDEX idx_scan_audit  ON audit_scans (audit_id);
CREATE INDEX idx_scan_status ON audit_scans (match_status);

-- 5. BELGE & EVRAK YÖNETİMİ
CREATE TABLE asset_documents (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_code             VARCHAR2(64 CHAR)  NOT NULL CONSTRAINT uk_docs_code UNIQUE,
    asset_id             NUMBER(19)         CONSTRAINT fk_docs_asset REFERENCES assets (id),
    asset_name           VARCHAR2(255 CHAR),
    document_type        VARCHAR2(64 CHAR)  NOT NULL,
    title                VARCHAR2(255 CHAR) NOT NULL,
    document_no          VARCHAR2(120 CHAR),
    file_name            VARCHAR2(180 CHAR) NOT NULL,
    file_size_kb         NUMBER(8)          DEFAULT 120 NOT NULL,
    issued_by            VARCHAR2(180 CHAR),
    valid_until          DATE,
    notes                VARCHAR2(500 CHAR),
    created_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_docs_asset ON asset_documents (asset_id);
CREATE INDEX idx_docs_type  ON asset_documents (document_type);

-- 6. SİSTEM DENETİM VE ONAY LOGLARI
CREATE TABLE system_audit_logs (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type          VARCHAR2(64 CHAR)  NOT NULL,
    entity_type          VARCHAR2(64 CHAR)  NOT NULL,
    entity_id            VARCHAR2(64 CHAR),
    actor_username       VARCHAR2(80 CHAR)  NOT NULL,
    actor_name           VARCHAR2(180 CHAR) NOT NULL,
    ip_address           VARCHAR2(64 CHAR)  DEFAULT '127.0.0.1' NOT NULL,
    description          VARCHAR2(1000 CHAR) NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_syslog_act  ON system_audit_logs (action_type);
CREATE INDEX idx_syslog_date ON system_audit_logs (created_at);

-- 7. SİSTEM PARAMETRELERİ VE AYARLAR
CREATE TABLE system_settings (
    param_key            VARCHAR2(80 CHAR)  PRIMARY KEY,
    param_value          VARCHAR2(500 CHAR) NOT NULL,
    param_group          VARCHAR2(64 CHAR)  NOT NULL,
    description          VARCHAR2(255 CHAR),
    updated_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

