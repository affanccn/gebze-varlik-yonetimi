-- 1. KURUMSAL MÜDÜRLÜKLER
CREATE TABLE departments (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR2(32 CHAR)  NOT NULL CONSTRAINT uk_departments_code UNIQUE,
    name          VARCHAR2(180 CHAR) NOT NULL CONSTRAINT uk_departments_name UNIQUE,
    manager_name  VARCHAR2(180 CHAR),
    phone         VARCHAR2(64 CHAR),
    email         VARCHAR2(120 CHAR),
    display_order NUMBER(5)          DEFAULT 0 NOT NULL,
    is_active     NUMBER(1)          DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_departments_active ON departments (is_active);

-- 2. ALT BİRİMLER & ŞEFLİKLER
CREATE TABLE sub_units (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  NUMBER(19)         NOT NULL CONSTRAINT fk_subunits_dept REFERENCES departments (id) ON DELETE CASCADE,
    parent_unit_id NUMBER(19)         CONSTRAINT fk_subunits_parent REFERENCES sub_units (id) ON DELETE SET NULL,
    code           VARCHAR2(48 CHAR)  NOT NULL CONSTRAINT uk_subunits_code UNIQUE,
    name           VARCHAR2(180 CHAR) NOT NULL,
    unit_type      VARCHAR2(64 CHAR)  DEFAULT 'Birim' NOT NULL,
    manager_name   VARCHAR2(180 CHAR),
    phone          VARCHAR2(64 CHAR),
    description    VARCHAR2(500 CHAR),
    is_active      NUMBER(1)          DEFAULT 1 NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_subunits_dept   ON sub_units (department_id);
CREATE INDEX idx_subunits_parent ON sub_units (parent_unit_id);

-- 3. HİZMET BİNALARI VE FİZİKSEL YERLEŞKELER
CREATE TABLE buildings (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR2(32 CHAR)  NOT NULL CONSTRAINT uk_buildings_code UNIQUE,
    name          VARCHAR2(180 CHAR) NOT NULL CONSTRAINT uk_buildings_name UNIQUE,
    building_type VARCHAR2(64 CHAR)  DEFAULT 'Hizmet Binası' NOT NULL,
    address       VARCHAR2(255 CHAR),
    phone         VARCHAR2(64 CHAR),
    total_floors  NUMBER(3)          DEFAULT 1 NOT NULL,
    description   VARCHAR2(500 CHAR),
    is_active     NUMBER(1)          DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_buildings_active ON buildings (is_active);

-- 4. BİNA KATLARI
CREATE TABLE floors (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id NUMBER(19)         NOT NULL CONSTRAINT fk_floors_building REFERENCES buildings (id) ON DELETE CASCADE,
    floor_code  VARCHAR2(32 CHAR)  NOT NULL,
    floor_name  VARCHAR2(120 CHAR) NOT NULL,
    floor_order NUMBER(3)          DEFAULT 0 NOT NULL,
    description VARCHAR2(500 CHAR),
    is_active   NUMBER(1)          DEFAULT 1 NOT NULL,
    CONSTRAINT uk_floors_bld_code UNIQUE (building_id, floor_code)
);

CREATE INDEX idx_floors_bld ON floors (building_id);

-- 5. ODALAR, OFİSLER, DEPOLAR VE TEKNİK ALANLAR
CREATE TABLE rooms (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id        NUMBER(19)         NOT NULL CONSTRAINT fk_rooms_bld REFERENCES buildings (id) ON DELETE CASCADE,
    floor_id           NUMBER(19)         NOT NULL CONSTRAINT fk_rooms_floor REFERENCES floors (id) ON DELETE CASCADE,
    room_number        VARCHAR2(32 CHAR)  NOT NULL,
    name               VARCHAR2(180 CHAR) NOT NULL,
    room_type          VARCHAR2(64 CHAR)  DEFAULT 'Personel Ofisi' NOT NULL,
    department_id      NUMBER(19)         CONSTRAINT fk_rooms_dept REFERENCES departments (id) ON DELETE SET NULL,
    sub_unit_id        NUMBER(19)         CONSTRAINT fk_rooms_subunit REFERENCES sub_units (id) ON DELETE SET NULL,
    responsible_person VARCHAR2(180 CHAR),
    capacity           NUMBER(5)          DEFAULT 4 NOT NULL,
    qr_code            VARCHAR2(120 CHAR) NOT NULL CONSTRAINT uk_rooms_qr UNIQUE,
    description        VARCHAR2(500 CHAR),
    is_active          NUMBER(1)          DEFAULT 1 NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_rooms_bld   ON rooms (building_id);
CREATE INDEX idx_rooms_floor ON rooms (floor_id);
CREATE INDEX idx_rooms_dept  ON rooms (department_id);
CREATE INDEX idx_rooms_type  ON rooms (room_type);

-- 6. VARLIK KATEGORİLERİ
CREATE TABLE asset_categories (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   NUMBER(19)         CONSTRAINT fk_categories_parent REFERENCES asset_categories (id) ON DELETE CASCADE,
    code        VARCHAR2(32 CHAR)  NOT NULL CONSTRAINT uk_categories_code UNIQUE,
    name        VARCHAR2(120 CHAR) NOT NULL CONSTRAINT uk_categories_name UNIQUE,
    icon        VARCHAR2(64 CHAR),
    description VARCHAR2(500 CHAR),
    is_active   NUMBER(1)          DEFAULT 1 NOT NULL
);

CREATE INDEX idx_categories_parent ON asset_categories (parent_id);

-- 7. PERSONEL TABLOSU
CREATE TABLE personnel (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number VARCHAR2(32 CHAR)  NOT NULL,
    first_name          VARCHAR2(80 CHAR)  NOT NULL,
    last_name           VARCHAR2(80 CHAR)  NOT NULL,
    full_name           VARCHAR2(160 CHAR) NOT NULL,
    title               VARCHAR2(100 CHAR) NOT NULL,
    department_id       NUMBER(19)         CONSTRAINT fk_pers_dept REFERENCES departments(id) ON DELETE SET NULL,
    sub_unit_id         NUMBER(19)         CONSTRAINT fk_pers_sub REFERENCES sub_units(id) ON DELETE SET NULL,
    room_id             NUMBER(19)         CONSTRAINT fk_pers_room REFERENCES rooms(id) ON DELETE SET NULL,
    phone               VARCHAR2(64 CHAR),
    email               VARCHAR2(120 CHAR),
    is_active           NUMBER(1)          DEFAULT 1 NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    is_deleted          NUMBER(1)          DEFAULT 0 NOT NULL,
    deleted_at          TIMESTAMP WITH TIME ZONE,
    deleted_by          VARCHAR2(80 CHAR)
);

CREATE UNIQUE INDEX uk_personnel_active_reg ON personnel (
    CASE WHEN is_deleted = 0 THEN registration_number ELSE NULL END
);
CREATE INDEX idx_personnel_reg      ON personnel (registration_number);
CREATE INDEX idx_personnel_dept     ON personnel (department_id);
CREATE INDEX idx_personnel_sub      ON personnel (sub_unit_id);
CREATE INDEX idx_personnel_room     ON personnel (room_id);
CREATE INDEX idx_personnel_active   ON personnel (is_active);
CREATE INDEX idx_personnel_dept_del ON personnel (department_id, is_deleted, id DESC);

-- 8. SİSTEM KULLANICILARI TABLOSU
CREATE TABLE system_users (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR2(64 CHAR)  NOT NULL CONSTRAINT uk_users_username UNIQUE,
    password_hash        VARCHAR2(255 CHAR) NOT NULL,
    full_name            VARCHAR2(160 CHAR) NOT NULL,
    email                VARCHAR2(120 CHAR),
    role                 VARCHAR2(32 CHAR)  NOT NULL,
    department_id        NUMBER(19)         CONSTRAINT fk_users_dept REFERENCES departments(id) ON DELETE SET NULL,
    personnel_id         NUMBER(19)         CONSTRAINT fk_users_personnel REFERENCES personnel(id) ON DELETE SET NULL,
    must_change_password NUMBER(1)          DEFAULT 0 NOT NULL,
    is_active            NUMBER(1)          DEFAULT 1 NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    failed_attempts      NUMBER(3)          DEFAULT 0 NOT NULL,
    locked_until         TIMESTAMP
);

CREATE INDEX idx_sys_users_dept ON system_users (department_id);
CREATE INDEX idx_sys_users_pers ON system_users (personnel_id);

-- 9. DEMİRBAŞ VE VARLIKLAR TABLOSU (Oracle 19c/21c/23ai Uyumlu CLOB IS JSON)
CREATE TABLE assets (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR2(64 CHAR)  NOT NULL,
    tif_code          VARCHAR2(64 CHAR),
    barcode           VARCHAR2(64 CHAR),
    name              VARCHAR2(255 CHAR) NOT NULL,
    category          VARCHAR2(120 CHAR) NOT NULL,
    brand_model       VARCHAR2(180 CHAR),
    serial_number     VARCHAR2(120 CHAR),
    unit_name         VARCHAR2(180 CHAR) NOT NULL,
    location_info     VARCHAR2(255 CHAR) NOT NULL,
    assignee_name     VARCHAR2(180 CHAR),
    status            VARCHAR2(40 CHAR)  NOT NULL,
    condition_status  VARCHAR2(40 CHAR)  DEFAULT 'Çok İyi' NOT NULL,
    acquisition_date  DATE,
    warranty_end_date DATE,
    estimated_value   NUMBER(15, 2)      DEFAULT 0,
    supplier          VARCHAR2(180 CHAR),
    notes             VARCHAR2(1000 CHAR),
    updated_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    department_id     NUMBER(19)         CONSTRAINT fk_assets_dept REFERENCES departments (id) ON DELETE SET NULL,
    sub_unit_id       NUMBER(19)         CONSTRAINT fk_assets_subunit REFERENCES sub_units (id) ON DELETE SET NULL,
    building_id       NUMBER(19)         CONSTRAINT fk_assets_bld REFERENCES buildings (id) ON DELETE SET NULL,
    floor_id          NUMBER(19)         CONSTRAINT fk_assets_floor REFERENCES floors (id) ON DELETE SET NULL,
    room_id           NUMBER(19)         CONSTRAINT fk_assets_room REFERENCES rooms (id) ON DELETE SET NULL,
    category_id       NUMBER(19)         CONSTRAINT fk_assets_category_fk REFERENCES asset_categories (id) ON DELETE SET NULL,
    is_active         NUMBER(1)          DEFAULT 1 NOT NULL,
    is_deleted        NUMBER(1)          DEFAULT 0 NOT NULL,
    deleted_at        TIMESTAMP WITH TIME ZONE,
    deleted_by        VARCHAR2(80 CHAR),
    lifecycle_status  VARCHAR2(40 CHAR)  DEFAULT 'KULLANIMDA' NOT NULL,
    specifications    CLOB               CONSTRAINT chk_assets_spec_json CHECK (specifications IS JSON)
);

CREATE UNIQUE INDEX uk_assets_active_code ON assets (
    CASE WHEN is_deleted = 0 THEN code ELSE NULL END
);
CREATE UNIQUE INDEX uk_assets_active_barcode ON assets (
    CASE WHEN is_deleted = 0 AND barcode IS NOT NULL THEN barcode ELSE NULL END
);
CREATE INDEX idx_assets_code        ON assets (code);
CREATE INDEX idx_assets_category    ON assets (category);
CREATE INDEX idx_assets_unit        ON assets (unit_name);
CREATE INDEX idx_assets_status      ON assets (status);
CREATE INDEX idx_assets_barcode     ON assets (barcode);
CREATE INDEX idx_assets_dept_id     ON assets (department_id);
CREATE INDEX idx_assets_bld_id      ON assets (building_id);
CREATE INDEX idx_assets_room_id     ON assets (room_id);
CREATE INDEX idx_assets_dept_scope  ON assets (department_id, is_deleted, id DESC);
CREATE INDEX idx_assets_lifecycle   ON assets (lifecycle_status, is_deleted);
CREATE INDEX idx_assets_category_id ON assets (category_id, is_deleted);

